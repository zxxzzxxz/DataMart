"""Isolated PostgreSQL fixtures shared by application and provider tests."""

import os
import uuid
from pathlib import Path

import psycopg2
import pytest
from psycopg2 import sql
from psycopg2.extensions import make_dsn

ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture(scope="session")
def isolated_database():
    dsn = os.environ.get("DATAMART_TEST_DSN")
    if not dsn:
        pytest.skip("Real PostgreSQL acceptance requires DATAMART_TEST_DSN")
    name = "datamart_acceptance_" + uuid.uuid4().hex
    admin = psycopg2.connect(dsn)
    admin.autocommit = True
    with admin.cursor() as cur:
        cur.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
    try:
        yield make_dsn(dsn, dbname=name)
    finally:
        with admin.cursor() as cur:
            cur.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = %s", (name,))
            cur.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(name)))
        admin.close()


@pytest.fixture(params=["psycopg2", "psycopg3"])
def database(isolated_database, request):
    if request.param == "psycopg3":
        import psycopg as driver
    else:
        driver = psycopg2

    def connect():
        return driver.connect(isolated_database, connect_timeout=5)

    connect.test_dsn = isolated_database
    connect.error_type = driver.Error
    connect.lock_error_type = driver.errors.LockNotAvailable

    conn = connect()
    try:
        with conn, conn.cursor() as cur:
            # The database name was generated by this fixture, never an existing warehouse.
            cur.execute("DROP SCHEMA IF EXISTS ods, dwh, dm, dwh_quarantine CASCADE")
            cur.execute((ROOT / "docker/warehouse-init/01_init.sql").read_text(encoding="utf-8"))
            for path in sorted((ROOT / "docker/warehouse-migrations").glob("V*.sql")):
                cur.execute(path.read_text(encoding="utf-8"))
    finally:
        conn.close()
    return connect
